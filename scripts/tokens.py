"""Writes ui/tokens.css from the design tokens in the old repository's design/figlib.py (colors in Light, Dark and
E-ink; the type scale; spacing, radius, touch sizes). One CSS variable per token, as FigCraft holds them.

    python scripts/tokens.py [path/to/design]

The reading face is Literata in the app (decided in review); the sheets use Merriweather because FigCraft has it built in.
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OLD = os.path.join(os.path.expanduser("~"), "github", "bible-workbench")
CANDIDATES = [os.path.join(OLD, "design"), os.path.join(OLD, ".claude", "worktrees", "design-layouts-e1b1df", "design")]
FAMILY = {"Inter": "var(--font-ui)", "Merriweather": "var(--font-read)", "Noto Sans Hebrew": "var(--font-heb)"}
WEIGHT = {"Regular": 400, "Medium": 500, "Semi Bold": 600, "Bold": 700}


def kebab(name):
    return "".join("-" + c.lower() if c.isupper() else c for c in name)


def main():
    design = sys.argv[1] if len(sys.argv) > 1 else next((p for p in CANDIDATES if os.path.exists(os.path.join(p, "figlib.py"))), None)
    if not design:
        sys.exit("No design/figlib.py found; pass the design folder")
    spec = importlib.util.spec_from_file_location("figlib", os.path.join(design, "figlib.py"))
    fig = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(fig)

    def block(mode_index):
        return "\n".join(f"  --{kebab(k)}: {v[mode_index]};  /* {v[3]} */" for k, v in fig.COLORS.items())

    type_lines = []
    for name, (family, style, size, lh, ls, what) in fig.TYPE.items():
        type_lines.append(f"  --type-{kebab(name)}: {WEIGHT[style]} {size}px/{lh}px {FAMILY[family]};  /* {what} */")
        if ls:
            type_lines.append(f"  --type-{kebab(name)}-tracking: {ls}px;")
    space = "\n".join(f"  --space-{i + 1}: {v}px;" for i, v in enumerate(fig.SPACE))
    radius = "\n".join(f"  --radius-{k}: {v}px;" for k, v in fig.RADIUS.items())
    touch = "\n".join(f"  --touch-{k}: {v}px;" for k, v in fig.TOUCH.items())

    css = f"""/* Generated by scripts/tokens.py from design/figlib.py. Do not edit by hand. */
:root {{
  --font-ui: "Inter", system-ui, sans-serif;
  --font-read: "Literata", "Iowan Old Style", Palatino, serif;
  --font-heb: "Noto Sans Hebrew", "SBL Hebrew", sans-serif;
{chr(10).join(type_lines)}
{space}
{radius}
{touch}
}}

/* Light */
:root {{
{block(0)}
}}

/* Dark: follows the system unless a theme is chosen */
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]):not([data-theme="eink"]) {{
{chr(10).join("  " + l for l in block(1).splitlines())}
  }}
}}
:root[data-theme="dark"] {{
{block(1)}
}}

/* E-ink */
:root[data-theme="eink"] {{
{block(2)}
}}
"""
    out = os.path.join(HERE, "..", "ui", "tokens.css")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(css)
    print("wrote", os.path.normpath(out), "from", design)


if __name__ == "__main__":
    main()
