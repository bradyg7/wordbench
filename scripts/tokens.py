"""Generate ui/tokens.css from the repository-owned design/tokens.json.

    python scripts/tokens.py          # write the generated stylesheet
    python scripts/tokens.py --check  # fail if it is stale
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "design", "tokens.json")
OUT = os.path.join(HERE, "..", "ui", "tokens.css")
FAMILY = {"Inter": "var(--font-ui)", "Merriweather": "var(--font-read)", "Noto Sans Hebrew": "var(--font-heb)"}
WEIGHT = {"Regular": 400, "Medium": 500, "Semi Bold": 600, "Bold": 700}


def kebab(name):
    return "".join("-" + c.lower() if c.isupper() else c for c in name)


def render(tokens):
    def block(mode_index):
        return "\n".join(f"  --{kebab(k)}: {v[mode_index]};  /* {v[3]} */" for k, v in tokens["colors"].items())

    type_lines = []
    for name, (family, style, size, lh, ls, what) in tokens["type"].items():
        type_lines.append(f"  --type-{kebab(name)}: {WEIGHT[style]} {size}px/{lh}px {FAMILY[family]};  /* {what} */")
        if ls:
            type_lines.append(f"  --type-{kebab(name)}-tracking: {ls}px;")
    space = "\n".join(f"  --space-{i + 1}: {v}px;" for i, v in enumerate(tokens["space"]))
    radius = "\n".join(f"  --radius-{k}: {v}px;" for k, v in tokens["radius"].items())
    touch = "\n".join(f"  --touch-{k}: {v}px;" for k, v in tokens["touch"].items())

    return f"""/* Generated by scripts/tokens.py from design/tokens.json. Do not edit by hand. */
:root {{
  --font-ui: "Inter", system-ui, sans-serif;
  --font-read: "Literata", "Iowan Old Style", Palatino, serif;
  --font-heb: "Noto Sans Hebrew", "SBL Hebrew", sans-serif;
{chr(10).join(type_lines)}
{space}
{radius}
{touch}
}}

/* Light */
:root {{
{block(0)}
}}

/* Dark: follows the system unless a theme is chosen */
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]):not([data-theme="eink"]) {{
{chr(10).join("  " + l for l in block(1).splitlines())}
  }}
}}
:root[data-theme="dark"] {{
{block(1)}
}}

/* E-ink */
:root[data-theme="eink"] {{
{block(2)}
}}
"""


def main():
    with open(DATA, encoding="utf-8") as f:
        css = render(json.load(f))
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            current = f.read()
        if current != css:
            sys.exit("ui/tokens.css is stale; run python scripts/tokens.py")
        print("ui/tokens.css is current")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(css)
    print("wrote ui/tokens.css from design/tokens.json")


if __name__ == "__main__":
    main()
