import { chromium } from '@playwright/test';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const out=resolve('site/public/demo');
const browser=await chromium.launch({channel:'msedge',args:['--disable-gpu']});
const context=await browser.newContext({viewport:{width:1280,height:800},deviceScaleFactor:1,recordVideo:{dir:resolve('release-staging/demo-video'),size:{width:1280,height:800}}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4185/?at=JHN.1');
await page.waitForFunction(()=>window.__wbReady);
await page.evaluate(()=>document.fonts.ready);
await page.waitForTimeout(1200);
await page.screenshot({path:out+'/reader.png'});
const fixture=JSON.parse(await readFile('ui/public/fixtures/JHN.1.json','utf8'));
const word=Object.entries(fixture.words).find(([key,value])=>key.startsWith('1.') && value.strong==='G3056');
if(!word)throw Error('No database-backed word fixture');
const [verse,index]=word[0].split('.').map(Number);
const k=await page.evaluate(([verse,index])=>window.__wb.drawn.v.findIndex((v,k)=>v===verse&&window.__wb.drawn.i[k]===index),[verse,index]);
await page.locator(`.w[data-k="${k}"]`).click();
await page.waitForTimeout(2500);
await page.screenshot({path:out+'/word-lookup.png'});
if (!await page.getByText("G3056 · Strong's", {exact:true}).isVisible()) throw Error('Lookup did not open');
await page.keyboard.press('Escape');

await page.locator('#reader .vn[data-v="1"]').click({button:'right'});
await page.getByRole('button',{name:'Open in a new tab',exact:true}).click();
await page.waitForTimeout(1200);
await page.evaluate(()=>window.__wb.open('PSA',119));
await page.waitForTimeout(1600);
await page.screenshot({path:out+'/parallel-readers.png'});
await page.mouse.move(650,330,{steps:20});
await page.mouse.wheel(0,450);await page.waitForTimeout(1600);
await page.mouse.wheel(0,-450);await page.waitForTimeout(1400);
const video=page.video();await context.close();
await video.saveAs(out+'/walkthrough.webm');
await browser.close();
await writeFile(out+'/capture.json',JSON.stringify({capturedAt:'2026-11-11',source:'Development interface at c65b9aa using CLI-generated Scripture fixtures and disposable study data',viewport:{width:1280,height:800},errors},null,2));
console.log(JSON.stringify({word:word[0],errors,output:out}));
